def _fill_placeholders(prompt):
    """Show the 'commitplaceholders' alias output and append any values the user enters."""
    print("\n📝 Placeholders for additional context:")
    try:
        result = subprocess.run(['git', 'commitplaceholders'], capture_output=True, text=True, check=True)
        placeholders_output = result.stdout
        print(placeholders_output.strip())
        placeholders = []
        in_section = False
        for line in placeholders_output.split('\n'):
            if line.startswith('## Placeholders for Manual Input:'):
                in_section = True
                continue
            if in_section and line.strip().endswith(':') and not line.startswith('##'):
                placeholders.append(line.strip())
    except subprocess.CalledProcessError as e:
        print(f"🚨 Error displaying placeholders: {e}")
        placeholders = []

    if placeholders:
        filled_values = {}
        print("\nEnter values for each placeholder (press Enter to skip):")
        for ph in placeholders:
            value = input(f"{ph} ").strip()
            if value:
                filled_values[ph] = value
        if filled_values:
            prompt += "\n\n## Filled Placeholders:"
            for ph, val in filled_values.items():
                prompt += f"\n{ph} {val}"
    return prompt


def _commit_with_regeneration(provider, target_model, prompt, args):
    """Generate → review/commit loop, with cloud fallback on Ollama exhaustion."""
    MAX_RETRIES = 2
    attempt = 0
    while attempt <= MAX_RETRIES:
        try:
            commit_message = provider.generate_commit_message(
                prompt, include_signature=args.watermark, model_name=target_model)
        except OllamaExhausted as e:
            provider = switch_to_cloud_or_exit(str(e))
            announce_provider(provider, args)
            provider.ensure_deps()
            provider.make_client()
            target_model = provider.pick_model(interactive=args.model)
            continue  # regenerate with the cloud provider (attempt count unchanged)

        result = make_git_commit(
            commit_message, dry_run=args.dry_run, review=args.review, push=args.push,
            add_all=(args.add_all or args.aa), can_regenerate=(attempt < MAX_RETRIES))

        if result == "REGENERATE":
            attempt += 1
            if attempt <= MAX_RETRIES:
                print(f"\n🔄 Regeneration requested (attempt {attempt}/{MAX_RETRIES})...")
            else:
                print(f"\n⚠️ Maximum regeneration attempts ({MAX_RETRIES}) reached.")
                print("   Using the last generated message.")
                make_git_commit(
                    commit_message, dry_run=args.dry_run, review=False, push=args.push,
                    add_all=(args.add_all or args.aa), can_regenerate=False)
                break
        else:
            break


def run(argv):
    args = build_arg_parser().parse_args(argv)

    # --- Provider resolution + lazy setup ---
    provider = resolve_provider(args)
    announce_provider(provider, args)
    provider.ensure_deps()
    provider.make_client()
    target_model = provider.pick_model(interactive=args.model)

    # --- Interactive staging ---
    if args.interactive_add:
        interactive_add(debug_mode=args.debug)

    # --- Stage specific files ---
    if args.files:
        print(f"📂 Staging specified files: {', '.join(args.files)}")
        for file in args.files:
            print(f"   ➕ Adding: {file}")
            try:
                run_git_with_ownership_fix(['git', 'add', file],
                                           operation_description=f"staging {file}", debug=args.debug)
            except subprocess.CalledProcessError:
                print(f"\n🚨 Failed to stage file: {file}")
                sys.exit(1)
        print("✅ File staging complete.\n")

    # --- Stage everything ---
    if args.add_all or args.aa:
        print("\n✅ --add-all flag detected. Staging all changes...")
        try:
            run_git_with_ownership_fix(['git', 'add', '.', '-v'],
                                       operation_description="staging all changes", debug=args.debug)
            print("---")
        except subprocess.CalledProcessError as e:
            print(f"\n🚨 Failed to stage changes: {e}")
            sys.exit(1)

    # --- Nothing staged? stop. ---
    if subprocess.run(['git', 'diff', '--staged', '--quiet']).returncode == 0:
        print("\n🤷 No changes staged for commit. Use 'git add' or pass filenames to this script.")
        sys.exit(0)

    # --- Build the prompt from 'git cinfo' (+ optional placeholders) ---
    prompt = get_prompt_from_git('cinfo')
    if args.fill_placeholders:
        prompt = _fill_placeholders(prompt)

    if args.debug:
        print("\n🐛 [DEBUG] Generated Prompt Preview:")
        print(f"{prompt[:500]}...\n" if len(prompt) > 500 else f"{prompt}\n")
        if getattr(provider, '_fallback_chain', None):
            print(f"🐛 [DEBUG] Fallback chain: {provider._fallback_chain}\n")

    # --- Generate + commit (with regeneration + cloud fallback) ---
    _commit_with_regeneration(provider, target_model, prompt, args)

    # --- Cleanup for the safe-preview combo ---
    if (args.add_all or args.aa) and args.dry_run:
        print("\n🧹 --add-all and --dry-run detected. Unstaging files to clean up...")
        subprocess.run(['git', 'restore', '--staged', '.'], check=True)
        print("✅ Cleanup complete. Staging area is clean.")


if __name__ == "__main__":
    run(sys.argv[1:])
