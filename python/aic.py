#!/usr/bin/env python3
"""
AI-powered Git commit message generator — one tool, many providers.

This single module replaces the old family of per-provider scripts
(aica.py / aicg.py / aico.py / aicl.py). It generates a conventional-commit
message from your staged changes using whichever AI provider you pick.

Providers (the "implementations" behind one shared framework):
  - Ollama (local)     — no API key, runs at localhost:11434          (--provider ollama)
  - Anthropic Claude   — ANTHROPIC_API_KEY                            (--provider anthropic)
  - Google Gemini      — GOOGLE_API_KEY / GEMINI_API_KEY              (--provider gemini)
  - OpenAI             — OPENAI_API_KEY                               (--provider openai)

Usage:
  git aic                 # auto-detect: Ollama (local) > Anthropic > Gemini > OpenAI
  git aic --cloud         # skip Ollama, use the best available cloud provider
  git aic --provider X    # force a specific provider (X = ollama|anthropic|gemini|openai)

All commit flags work the same across every provider:
  FILES...                stage these files first
  -a / --add-all          stage all changes (git add .)
  -i / --interactive-add  stage interactively via 'git adi' (fzf)
  -d / --dry-run          print the message, do not commit
  -r / --review           review before committing  [y/n/e/r]
  -p / --push             push after a successful commit
  -m / --model            pick the model interactively
  -f / --fill-placeholders   fill the 'cinfo' placeholders for extra context
  -w / --watermark        append a "Generated by ..." signature
  -v / --debug            verbose logging

Design: a `Provider` abstract base class declares the contract; each concrete
provider implements only its own API calls. The shared git framework
(staging, prompt building, the review/commit loop) lives here exactly once.
Third-party SDKs are imported lazily — only the chosen provider's packages are
installed/loaded, so an OpenAI-only user never pulls in the Anthropic SDK.
"""

