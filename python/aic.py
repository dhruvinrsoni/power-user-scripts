CLOUD_ORDER = ["anthropic", "gemini", "openai"]


def get_provider(name):
    """Factory: instantiate a provider by registry name."""
    return PROVIDERS[name]()


def detect_cloud_provider():
    """Return the first cloud provider with credentials set, else None."""
    for key in CLOUD_ORDER:
        provider = get_provider(key)
        if provider.is_available():
            return provider
    return None


def resolve_provider(args):
    """Pick a provider from --provider, or auto-detect (Ollama-first unless --cloud)."""
    if args.provider:
        return get_provider(args.provider)

    if not args.cloud:
        # Ollama-first: it must be reachable in auto mode (use --cloud to skip it).
        ok, reason = is_ollama_available()
        if not ok:
            if not ollama_retry_or_exit(reason, OLLAMA_BASE_URL):
                sys.exit(1)
        return OllamaProvider()

    cloud = detect_cloud_provider()
    if not cloud:
        print_status("\n🚨 No AI provider available.")
        print_status("   --cloud mode is active (Ollama bypassed).")
        print_status("   Set one of the following environment variables:")
        print_status("   • ANTHROPIC_API_KEY  — Anthropic Claude")
        print_status("   • GOOGLE_API_KEY or GEMINI_API_KEY  — Google Gemini")
        print_status("   • OPENAI_API_KEY  — OpenAI")
        sys.exit(1)
    return cloud


def switch_to_cloud_or_exit(reason):
    """Offer to switch to a cloud provider after Ollama exhaustion (msvcrt y/n)."""
    cloud = detect_cloud_provider()
