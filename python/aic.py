def print_status(msg, end='\n'):
    """Print to stderr so it doesn't pollute captured stdout in pipelines."""
    print(msg, file=sys.stderr, flush=True, end=end)


def mask_key(value, show=4):
    """Return a masked secret: first N + *** + last N chars."""
    if not value or len(value) <= show * 2:
        return '***'
    return f"{value[:show]}{'*' * 8}{value[-show:]}"


def _suppress_ssl_warnings():
    """Silence urllib3 InsecureRequestWarning (we use verify=False on Windows)."""
    try:
        import urllib3
        urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)
    except Exception:
        pass


def format_size(size_bytes):
    """Convert bytes to a human-readable size string (e.g. '2.0 GB', '621 MB')."""
    if not size_bytes:
        return "? GB"
    gb = size_bytes / (1024 ** 3)
    if gb >= 1.0:
        return f"{gb:.1f} GB"
    mb = size_bytes / (1024 ** 2)
    return f"{mb:.0f} MB"


def is_ollama_available(base_url=None, timeout=2):
    """
    Probe GET /api/tags to check if Ollama is running. Stdlib only (urllib).
    Returns (True, None) on success, or (False, reason_string) on failure.
    """
    base_url = base_url or OLLAMA_BASE_URL
    try:
        req = urllib.request.urlopen(f"{base_url}/api/tags", timeout=timeout)
        return (True, None) if req.status == 200 else (False, f"Ollama returned HTTP {req.status}")
    except urllib.error.HTTPError as e:
        return (False, f"Ollama returned HTTP {e.code}")
    except urllib.error.URLError as e:
        if isinstance(e.reason, ConnectionRefusedError):
            return (False, "Connection refused (Ollama not running?)")
        if isinstance(e.reason, (TimeoutError, OSError)) and 'timed out' in str(e.reason):
            return (False, f"Connection timed out after {timeout}s (Ollama unresponsive?)")
        return (False, f"Network error: {e.reason}")
    except Exception as e:
        return (False, f"Unexpected error: {e}")


def ollama_retry_or_exit(reason, base_url, auto_retries=1):
    """Show why Ollama failed, auto-retry, then return True if it came back."""
    print_status(f"\n⚠️  Ollama: {reason}")
    for attempt in range(1, auto_retries + 1):
        print_status(f"🔄 Retrying Ollama... (attempt {attempt})")
        time.sleep(2)
        ok, reason = is_ollama_available(base_url=base_url)
        if ok:
            print_status("✅ Ollama is back!")
            return True
        print_status(f"⚠️  Ollama: {reason}")
    print_status("   Auto-retry exhausted.")
    print_status("   To use cloud instead: aic --cloud  (or aic -c)")
    print_status("   To fix Ollama: ollama serve  (then re-run aic)")
    return False


