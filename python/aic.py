class Provider(abc.ABC):
    """Abstract base: the contract every AI provider must satisfy."""
    name = "Provider"
    icon = "🤖"
    env_vars = []          # env keys that signal availability (empty for Ollama)
    pip_deps = []          # packages to install lazily for this provider
    default_model = None

    def is_available(self):
        """Default: available if any of its env vars is set."""
        return any(os.environ.get(v) for v in self.env_vars)

    def ensure_deps(self):
        """Install this provider's third-party packages exactly once (lazy)."""
        if getattr(self, '_deps_ready', False):
            return
        if self.pip_deps:
            dependency_manager.require(list(self.pip_deps))
        self._deps_ready = True

    def pick_model(self, interactive):
        """Default model selection: interactive picker, else the provider default."""
        if interactive:
            model = self.select_custom_model()
            print(f"🎯 Using model: {model}\n")
            return model
        return self.default_model

    @abc.abstractmethod
    def make_client(self):
        """Read credentials and build any API client. Imports the SDK lazily."""

    @abc.abstractmethod
    def get_available_models(self):
        """Return the provider's list of usable models."""

    @abc.abstractmethod
    def select_custom_model(self):
        """Interactively pick a model; return its id."""

    @abc.abstractmethod
    def generate_commit_message(self, prompt, include_signature, model_name):
        """Call the provider's API and return a cleaned commit message string."""


class AnthropicProvider(Provider):
    name = "Anthropic Claude"
    icon = "🟠"
    env_vars = ["ANTHROPIC_API_KEY"]
    pip_deps = ["anthropic", "httpx"]
    default_model = "claude-haiku-4-5-20251001"

    def make_client(self):
        import anthropic
        import httpx
        _suppress_ssl_warnings()
        try:
            key = os.environ["ANTHROPIC_API_KEY"]
        except KeyError:
            print("\n🚨 Error: ANTHROPIC_API_KEY environment variable is not set.")
            print("   Please set ANTHROPIC_API_KEY in your environment.")
            print("   Get your API key from: https://console.anthropic.com/")
            sys.exit(1)
        # SSL verification disabled to avoid certificate issues on Windows.
        self.client = anthropic.Anthropic(api_key=key, http_client=httpx.Client(verify=False))

    def get_available_models(self):
        try:
            models_data = self.client.models.list()
            generation_models = [m for m in models_data.data if m.id.startswith('claude-')]
            generation_models.sort(key=lambda x: x.id, reverse=True)
            return generation_models
        except Exception as e:
            print(f"\n🚨 Error fetching models: {e}")
            return []

    def select_custom_model(self):
        print("🔍 Fetching available models for your API key...")
        models = self.get_available_models()
        if not models:
            print("⚠️ Could not fetch models or no Claude models found.")
            print(f"   Falling back to default: {self.default_model}")
            return self.default_model
        print("\n--- 🤖 Available Anthropic Claude Models ---")
        for idx, model in enumerate(models, 1):
            display_name = getattr(model, 'display_name', model.id)
            print(f"  [{idx:2}] {model.id:<45} | {display_name}")
        while True:
            try:
                choice = input(f"\nSelect model [1-{len(models)}] or press Enter for default ({self.default_model}): ").strip()
                if not choice:
                    print(f"✅ Using default: {self.default_model}")
                    return self.default_model
                idx = int(choice) - 1
                if 0 <= idx < len(models):
                    print(f"✅ Selected: {models[idx].id}")
                    return models[idx].id
                print(f"❌ Please enter a number between 1 and {len(models)}")
            except ValueError:
                print("❌ Invalid input. Please enter a number.")
            except KeyboardInterrupt:
                print(f"\n\n⚠️ Selection cancelled. Using default: {self.default_model}")
                return self.default_model

    def generate_commit_message(self, prompt, include_signature, model_name):
        import anthropic
        print(f"✨ Asking {model_name} to generate the commit message...")
        context_input = (f"Analyze the following git context and generate the message.\n\n"
                         f"--- START GIT CONTEXT ---\n{prompt}\n--- END GIT CONTEXT ---")
        try:
            response = self.client.messages.create(
                model=model_name, max_tokens=1024, system=STRICT_INSTRUCTIONS,
                messages=[{"role": "user", "content": context_input}])
            raw_text = response.content[0].text.strip()
            sig = "--Generated by Anthropic Claude." if include_signature else None
            return _clean_message(raw_text, sig)
        except anthropic.RateLimitError:
            print("\n🚨 Rate Limit Exceeded (429 Too Many Requests)")
            print("   You've hit the Anthropic API rate limit.")
            print("\n💡 Solutions:")
            print("   1. Wait a few minutes before trying again")
            print("   2. Check usage/limits at: https://console.anthropic.com/")
            print("   3. Add credits or upgrade your plan if needed")
            sys.exit(1)
        except anthropic.APIError as e:
            print(f"\n🚨 Anthropic API Error: {e}")
            sys.exit(1)
        except anthropic.AnthropicError as e:
            print(f"\n🚨 Anthropic Error: {e}")
            sys.exit(1)
        except Exception as e:
            print(f"\n🚨 An unexpected error occurred: {e}")
            sys.exit(1)


class GeminiProvider(Provider):
    name = "Google Gemini"
    icon = "🔵"
    env_vars = ["GOOGLE_API_KEY", "GEMINI_API_KEY"]
    pip_deps = ["requests"]
    default_model = "gemini-2.0-flash"

    def make_client(self):
        _suppress_ssl_warnings()
        self.api_key = os.environ.get("GOOGLE_API_KEY") or os.environ.get("GEMINI_API_KEY")
        if not self.api_key:
            print("\n🚨 Error: Neither GOOGLE_API_KEY nor GEMINI_API_KEY environment variable is set.")
            print("   Please set GOOGLE_API_KEY (preferred) or GEMINI_API_KEY in your environment.")
            print("   Get your API key from: https://aistudio.google.com/app/apikey")
            sys.exit(1)

    def get_available_models(self):
        import requests
        url = "https://generativelanguage.googleapis.com/v1beta/models"
        headers = {'Content-Type': 'application/json', 'X-goog-api-key': self.api_key}
        try:
            response = requests.get(url, headers=headers, verify=False, timeout=15)
            response.raise_for_status()
            models_data = response.json().get('models', [])
            return [
                m for m in models_data
                if 'generateContent' in m.get('supportedGenerationMethods', [])
                and 'models/' in m['name']
                and not any(x in m['name'] for x in ['embedding', 'aqa', 'text-moderation'])
            ]
        except Exception as e:
            print(f"\n🚨 Error fetching models: {e}")
            return []

    def select_custom_model(self):
        print("🔍 Fetching available models for your API key...")
        models = self.get_available_models()
        if not models:
            print("⚠️ Could not fetch models or no generation models found.")
            print(f"   Falling back to default: {self.default_model}")
            return self.default_model
